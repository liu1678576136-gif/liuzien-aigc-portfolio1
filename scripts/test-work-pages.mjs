import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve, join, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "vite";
import react from "@vitejs/plugin-react";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
const output = resolve("outputs/work-page-render");
assert(output.startsWith(process.cwd() + sep));
await mkdir(output, { recursive: true });
const entry = join(output, "entry.jsx");
await writeFile(entry, 'export { WorkPage } from "../../src/components/StudioPortfolio.jsx";\nexport { BackgroundMusicProvider } from "../../src/components/BackgroundMusicProvider.jsx";\nexport { LocaleProvider } from "../../src/LocaleContext.jsx";\n');
await build({ configFile: false, plugins: [react()], logLevel: "error", build: { ssr: entry, outDir: output, emptyOutDir: false } });
globalThis.window = { location: { search: "" } };
const { WorkPage, LocaleProvider, BackgroundMusicProvider } = await import(pathToFileURL(join(output, "entry.js")).href);
const render = route => renderToStaticMarkup(createElement(LocaleProvider, null, createElement(BackgroundMusicProvider, null, createElement(WorkPage, { route, onNavigate() {}, onBack() {}, onHome() {} }))));
const index = render({ kind: "works", category: "all" });
assert(index.includes('href="#/work/lze-workbench"'));
assert(!index.includes("video-scroll-track") && !index.includes("data-stream-src") && !index.includes("film.mp4"), "Subpages must never mount the scrolling scene videos");
assert.equal((index.match(/data-background-music/g) || []).length, 1, "One persistent player owns the music");
assert.equal((index.match(/<audio/g) || []).length, 1, "Headers must not create another music player");
const posters = render({ kind: "works", category: "poster" });
assert(posters.includes("电商海报")); assert(!posters.includes('href="#/work/lze-workbench"'));
const detail = render({ kind: "work", id: "lze-workbench" });
assert(detail.includes("lze-workbench-demo.mp4") && detail.includes('preload="metadata"'));
assert(!detail.includes("data-stream-src"));
assert(render({ kind: "work", id: "missing-project" }).includes("未找到这件作品"));
window.location.search = "?lang=en";
assert(render({ kind: "works", category: "all" }).includes("ALL WORK"));
console.log("Rendered work index, poster category, original-media detail, missing project and English page; background scenes are absent from all work subpages.");
